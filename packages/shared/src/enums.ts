/**
 * What the database calls a thing, and what a person calls it.
 *
 * Every state on this platform is a string in a CHECK constraint —
 * `PARTIALLY_PAID`, `READY_FOR_REVIEW`, `FARMERS_COOPERATIVE` — and both
 * front ends rendered them by taking the underscores out. That is English
 * whatever language the app is set to, and it is not always good English
 * either: an officer working in Hausa read "partially paid" and "farmers
 * cooperative" in the middle of Hausa sentences, and a status badge is
 * exactly the place somebody looks when they are in a hurry.
 *
 * WHY KEYED BY VALUE RATHER THAN BY COLUMN. The same word means the same
 * thing wherever it appears: a PENDING device and a PENDING refund are both
 * waiting, and the badge sits beside the noun that says which. Keying by
 * `table.column` would triple the dictionary to say "Ana jira" three times,
 * and every one of those copies could drift from the others. If a value ever
 * does need different words in two places, this is where that exception
 * would be written down, and it would be visible.
 *
 * `check-enum-labels.test.ts` reads the CHECK constraints out of the live
 * schema and fails if any allowed value is missing from this map, so a state
 * added to the database tomorrow cannot reach a screen in English.
 */

